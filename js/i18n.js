/**
 * Detect user device language
 */
function detectUserLanguage() {
    try {
        const saved = localStorage.getItem('app_user_lang');
        if (saved && SUPPORTED_LANGS.includes(saved)) {
            return saved;
        }
    } catch (e) {}

    const browserLangs = (navigator.languages && navigator.languages.length > 0)
        ? navigator.languages
        : [navigator.language || ''];

    for (const raw of browserLangs) {
        if (!raw) continue;
        const l = raw.toLowerCase();
        if (l.startsWith('zh-tw') || l.startsWith('zh-hk') || l.startsWith('zh-mo') || l.includes('hant')) {
            return 'zh-TW';
        }
        if (l.startsWith('zh')) {
            return 'zh-CN';
        }
        if (l.startsWith('ja')) {
            return 'ja';
        }
        if (l.startsWith('en')) {
            return 'en';
        }
    }

    // Default to English if device language is not in supported list
    return DEFAULT_FALLBACK_LANG;
}

/**
 * Translate key with optional parameter interpolation
 */
function t(key, params = {}) {
    const dict = I18N_DICTIONARY[currentLang] || I18N_DICTIONARY[DEFAULT_FALLBACK_LANG];
    let text = dict[key];
    if (text === undefined) {
        text = I18N_DICTIONARY[DEFAULT_FALLBACK_LANG]?.[key] || key;
    }
    for (const [k, v] of Object.entries(params)) {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    }
    return text;
}

/**
 * Apply all translations to DOM
 */
function applyTranslations(lang = currentLang) {
    currentLang = lang;
    document.documentElement.lang = lang;

    // 1. Update title
    document.title = t('app_title');

    // 2. Update text content for elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const val = t(key);
        if (val !== undefined) {
            el.textContent = val;
        }
    });

    // 3. Update HTML content for elements with data-i18n-html
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        const val = t(key);
        if (val !== undefined) {
            el.innerHTML = val;
        }
    });

    // 4. Update language selector element
    const langSel = document.getElementById('lang-selector');
    if (langSel && langSel.value !== lang) {
        langSel.value = lang;
    }

    // 5. Update dimension tip text if present
    const tipEl = document.getElementById('card-dimension-tip');
    if (tipEl && typeof currentTemplate !== 'undefined') {
        const dimMap = {
            slave: t('dim_slave'),
            bbc: t('dim_bbc'),
            cert: t('dim_cert'),
            bimbo: t('dim_bimbo')
        };
        if (dimMap[currentTemplate]) {
            tipEl.innerText = dimMap[currentTemplate];
        }
    }

    // 6. Update template specific language structures
    if (typeof updateBbcKinksLanguage === 'function') {
        updateBbcKinksLanguage(lang);
    }
    if (typeof updateBimboRulesLanguage === 'function') {
        updateBimboRulesLanguage(lang);
    }
    if (typeof updateCertTermsLanguage === 'function') {
        updateCertTermsLanguage(lang);
    }
    if (typeof loadDefaultPersonaForLanguage === 'function') {
        ['slave', 'bbc', 'cert', 'bimbo'].forEach(tpl => {
            loadDefaultPersonaForLanguage(tpl, lang);
        });
    }
}

/**
 * Change language programmatically or from UI select
 */
function changeLanguage(lang) {
    if (!SUPPORTED_LANGS.includes(lang)) {
        lang = DEFAULT_FALLBACK_LANG;
    }
    currentLang = lang;
    try {
        localStorage.setItem('app_user_lang', lang);
    } catch (e) {}

    applyTranslations(lang);

    // Track language change in analytics if available
    if (typeof trackEvent === 'function') {
        trackEvent('language_change', {
            selected_language: lang
        });
    }
}

/**
 * Initialize i18n system on startup
 */
function initI18n() {
    const detected = detectUserLanguage();
    changeLanguage(detected);
}
